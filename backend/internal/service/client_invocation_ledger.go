type ClientInvocationDispatchBinding struct {
	AccountID    int64
	Platform     string
	ModelID      string
	Protocol     string
	PayloadHash  string
	CounterProof *ClientInvocationCounterProof
	SearchProof  *ClientInvocationSearchProof
}

// Outcome deliberately contains no upstream response, headers, costs or claimed
// settlement state. A future execution adapter must normalize only owned text or
// a fixed error code after obtaining its actual completion/usage acknowledgment.
type ClientInvocationOutcome struct {
	Search       *ClientSearchOutput `json:"search,omitempty"`
	State        string              `json:"state"`
	Text         *string             `json:"text,omitempty"`
	FinishReason string              `json:"finishReason,omitempty"`
	ErrorCode    string              `json:"errorCode,omitempty"`
}

type ClientInvocationClaim struct {
	Record *ClientInvocationRecord `json:"-"`
	Owned  bool                    `json:"-"`
}

// Reserve/Get/StartDispatch require a fresh, persisted grant and exact owner
// scope. PrepareDispatch may create attempt 2 only after durable proof that
// attempt 1 was not dispatched; it never creates an unbounded retry chain.
// Finish uses the private attempt capability so logout or grant expiry cannot
// discard an already dispatched request's eventual completion. It never sends
// anything, and no public handler may accept an owner token from a client.
type ClientInvocationLedgerRepository interface {
	Reserve(context.Context, *ClientGatewayGrant, *ClientInvocationReservation) (*ClientInvocationClaim, error)
	Get(context.Context, *ClientGatewayGrant, string, string) (*ClientInvocationRecord, error)
	PrepareDispatch(context.Context, *ClientGatewayGrant, string, string, ClientInvocationDispatchBinding) (*ClientInvocationRecord, error)
	StartDispatch(context.Context, *ClientGatewayGrant, string, string, ClientInvocationDispatchBinding) (*ClientInvocationRecord, error)
	MarkPreparedNotDispatched(context.Context, string, string) (*ClientInvocationRecord, error)
	MarkUnknown(context.Context, string, string) (*ClientInvocationRecord, error)
	Finish(context.Context, string, string, ClientInvocationOutcome) (*ClientInvocationRecord, error)
}

func ValidateClientInvocationOutcome(outcome ClientInvocationOutcome) bool {
	if outcome.FinishReason != "" && (outcome.State != ClientInvocationSucceeded || outcome.Search != nil ||
		!clientContains([]string{"stop", "length", "content_filter", "tool_calls"}, outcome.FinishReason)) {
		return false
	}
	if outcome.State == ClientInvocationSucceeded {
		if outcome.Search != nil {
			return outcome.Text == nil && outcome.ErrorCode == "" && ValidateClientSearchOutput(outcome.Search)
		}
		return outcome.Text != nil && outcome.ErrorCode == "" && utf8.ValidString(*outcome.Text) && len(*outcome.Text) <= ClientInvocationMaxBytes
	}
	return outcome.State == ClientInvocationFailed && outcome.Text == nil && outcome.Search == nil && clientContains([]string{
		"MODEL_PARAMETERS_INVALID", "MODEL_QUOTA_EXHAUSTED", "MODEL_ROUTE_REVOKED", "MODEL_CONFIG_CHANGED",
		"UPSTREAM_UNAVAILABLE", "RATE_LIMITED", "INTERNAL_ERROR",
	}, outcome.ErrorCode)
}
