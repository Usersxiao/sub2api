// ClientInvocationReservation is generated by the server after strict admission.
// Neither the dispatch capability nor the input fingerprint is a public receipt.
type ClientInvocationReservation struct {
	InvocationID       string `json:"-"`
	ProjectID          string `json:"-"`
	RequestID          string `json:"-"`
	RouteID            string `json:"-"`
	Operation          string `json:"-"`
	ConfigVersion      string `json:"-"`
	EntitlementVersion string `json:"-"`
	Fingerprint        string `json:"-"`
	BillingIdentityID  int64  `json:"-"`
	GroupID            int64  `json:"-"`
	OwnerToken         string `json:"-"`
}

